<script type="text/javascript">
    function registro() {
        var user = document.getElementById("user").value;
        var email = document.getElementById("email").value;
        var pass = document.getElementById("pass").value;
        fetch('CriarUtilizador.php', {
            method: 'POST',
            headers: {
                'Content-Type': 'application/x-www-form-urlencoded'
            },
            body: `utilizador=${encodeURIComponent(user)}&email=${encodeURIComponent(email)}&passe=${encodeURIComponent(pass)}`
        })
        .then(response => response.text())
        .then(data => {
            if (data.includes("login.php")) {
                window.location.href = "http://localhost/SiteF1Test/HTML/PHP/login.php";
            } else {
                window.location.href = "http://localhost/SiteF1Test/HTML/PHP/login.php";
            }
        })
        .catch(error => console.error('Erro:', error));
    }

    document.querySelector('.login').addEventListener('click', function(event) {
        event.preventDefault();
        registro();
    });
</script>